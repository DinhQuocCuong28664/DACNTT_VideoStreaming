/**
 * Builds the raw-data tables of Appendix D from the final-configuration runs
 * (docs/results/runs/2026-11-0[45]-v2-*.json), so every number in the appendix comes from the same
 * records as the charts of chapter 6 (see build-v2-chart-data.mjs).
 *
 *   report/generated/tab-v2-ttff.tex        requests before the first frame, per step
 *   report/generated/tab-v2-qoe.tex         playback runs under three network profiles
 *   report/generated/tab-v2-bitrate.tex     declared and delivered bit rate, three videos
 *   report/generated/tab-v2-transcode.tex   the twelve transcoding runs by file size
 *   report/generated/tab-v2-four-hour.tex   steps of the four-hour video
 *   report/generated/tab-v2-burst.tex       one hundred simultaneous uploads
 *   report/generated/tab-v2-api.tex         API latency by phase
 *   report/generated/tab-v2-lambda.tex      function log of the API run and the burst
 *   report/generated/tab-v2-prices.tex      list prices used by the cost comparison
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const RUNS = path.join(ROOT, 'docs', 'results', 'runs');
const OUT = path.join(ROOT, 'report', 'generated');
const read = (name) => JSON.parse(fs.readFileSync(path.join(RUNS, name), 'utf8'));
const HEADER = '% Generated by docs/diagrams/svg/build-v2-appendix-tables.mjs; do not edit by hand.\n';

const fix = (v, d = 1) => (v === null || v === undefined ? '--' : Number(v).toFixed(d));
const median = (a) => { const s = [...a].sort((x, y) => x - y); return s[Math.floor(s.length / 2)]; };
const nearestRank = (a, p) => { const s = [...a].sort((x, y) => x - y); return s[Math.max(0, Math.ceil((p / 100) * s.length) - 1)]; };

/** Writes one table float; `spec` is the column spec, `head` the header cells, `rows` arrays of cells. */
function table(file, { caption, label, spec, head, headTex, rows, size = '\\footnotesize', sep, long = false }) {
  const headLine = headTex ?? `${head.map((h) => `\\textbf{${h}}`).join(' & ')} \\\\`;
  const sepLine = sep ? `\\setlength{\\tabcolsep}{${sep}pt}\n` : '';
  const body = rows.map((r) => (r === 'mid' ? '\\midrule' : `${r.join(' & ')} \\\\`)).join('\n');
  const tex = long
    ? `${HEADER}\\begin{${size.slice(1)}}
\\begin{longtable}{${spec}}
\\caption{${caption}}\\label{${label}}\\\\
\\toprule
${headLine}
\\midrule
\\endfirsthead
\\toprule
${headLine}
\\midrule
\\endhead
\\bottomrule
\\endfoot
${body}
\\end{longtable}
\\end{${size.slice(1)}}
`
    : `${HEADER}\\begin{table}[H]
\\centering
\\caption{${caption}}
\\label{${label}}
${size}
${sepLine}\\begin{tabular}{${spec}}
\\toprule
${headLine}
\\midrule
${body}
\\bottomrule
\\end{tabular}
\\end{table}
`;
  fs.writeFileSync(path.join(OUT, file), tex);
  console.log('wrote', file);
}

// ── Requests before the first frame ───────────────────────────────────────
{
  const run = read('2026-11-04-v2-ttff.json').runs[0];
  const first = Object.fromEntries(run.samples[0].steps.map((s) => [s.name, s.ms]));
  const names = { grant: 'Playback grant (API)', master: 'Master playlist (CDN)', playlist: 'Rendition playlist (CDN)', key: 'Key (API)', segment: 'First segment (CDN)' };
  const row = (label, f, s) => [label, fix(f), fix(s.mean), fix(s.p50), fix(s.p95), fix(s.min), fix(s.max)];
  table('tab-v2-ttff.tex', {
    caption: `Requests before the first frame of the ${run.video.rendition} rendition, in milliseconds; the first request and ${run.summary_ms.n} that followed it`,
    label: 'tab:raw-ttff',
    spec: 'l r r r r r r',
    head: ['STEP', 'FIRST', 'MEAN', 'MEDIAN', '95TH PCT.', 'MIN', 'MAX'],
    rows: [
      ...Object.keys(names).map((k) => row(names[k], first[k], run.per_step_ms[k])),
      'mid',
      row('Total', run.first_sample_ms, run.summary_ms),
    ],
  });
}

// ── Playback runs ─────────────────────────────────────────────────────────
{
  const profiles = [['unthrottled', 'Unthrottled'], ['fast3g', 'Fast 3G'], ['slow3g', 'Slow 3G']];
  const rows = [];
  profiles.forEach(([key, name], i) => {
    const d = read(`2026-11-04-v2-qoe-${key}.json`);
    if (i > 0) rows.push('mid');
    d.runsDetail.forEach((r, j) => {
      const res = d.p1203Mode0Input[j].I13.segments[0].resolution.replace('x', '$\\times$');
      rows.push([j === 0 ? name : '', j + 1, fix(r.startupDelaySec, 2), r.stallCount, fix(r.stallTotalSec, 1), fix(r.averageBitrateBps / 1000, 0), res]);
    });
  });
  table('tab-v2-qoe.tex', {
    caption: 'Playback runs of 60 seconds under three network profiles',
    label: 'tab:raw-qoe',
    spec: 'l c r c r r l',
    head: ['PROFILE', 'RUN', 'START-UP, S', 'STALLS', 'STALLED, S', 'KBIT/S', 'RUNG SHOWN'],
    rows,
  });
}

