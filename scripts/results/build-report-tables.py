#!/usr/bin/env python3
"""Sinh bảng LaTeX và mục lục số liệu từ dữ liệu đo trong docs/results.

Nguồn duy nhất của số liệu hiệu năng chuyển mã là các tệp JSON:

  - docs/results/runs/*.json        các lượt đo mới (có `schema`, `runs`)
  - docs/results/transcode-timing.json   các lượt đo đường một-job (tháng 8)

Đầu ra:

  - report/generated/*.tex   chỉ phần `tabularx`; chương báo cáo bọc quanh bằng
                             \\begin{table}, \\caption (đề bảng nằm TRÊN) và \\label
  - docs/results/INDEX.md    bảng "bảng báo cáo -> tệp số liệu" và danh sách lượt đo

Số trong báo cáo vì thế không gõ tay: sửa JSON rồi chạy lại script này.

    PYTHONUTF8=1 python scripts/results/build-report-tables.py
    PYTHONUTF8=1 python scripts/results/build-report-tables.py --check   # lỗi nếu tệp sinh ra khác bản đã commit
"""

import argparse
import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RUNS_DIR = ROOT / "docs" / "results" / "runs"
LEGACY = ROOT / "docs" / "results" / "transcode-timing.json"
OUT_DIR = ROOT / "report" / "generated"
INDEX = ROOT / "docs" / "results" / "INDEX.md"

HEADER = "% GENERATED by scripts/results/build-report-tables.py from docs/results. Do not edit by hand.\n"
LEGACY_LABELS = {"100mb": "100 MB", "500mb": "500 MB", "1gb": "1 GB"}


def load_runs():
    runs = []
    for path in sorted(RUNS_DIR.glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        for run in data.get("runs", []):
            run = dict(run)
            run["_file"] = path.relative_to(ROOT).as_posix()
            runs.append(run)
    return runs


def minutes(seconds, digits=1):
    return f"{seconds / 60:.{digits}f}"


def esc(text):
    return str(text).replace("\\", "\\textbackslash{}").replace("_", "\\_").replace("&", "\\&").replace("%", "\\%").replace("#", "\\#")


def table(colspec, header, rows):
    lines = [HEADER.rstrip("\n"), "\\begin{tabularx}{\\textwidth}{" + colspec + "}", "\\toprule"]
    lines.append(" & ".join("\\textbf{" + h + "}" for h in header) + " \\\\")
    lines.append("\\midrule")
    for row in rows:
        lines.append(" & ".join(row) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabularx}", ""]
    return "\n".join(lines)


def env_name(run):
    return {"production": "production", "staging": "staging"}.get(run["environment"], run["environment"])


def table_scaling_25min(runs):
    """Một video 25 phút, đường chia đoạn, từng cấu hình đoạn."""
    picked = [
        r for r in runs
        if r["path"] == "chunked" and r["video"]["label"] == "25min-1080p"
        and r["concurrency"] == 1 and "end_to_end" in r["timings_s"]
    ]
    def capacity(r):
        c = r.get("capacity") or {}
        return int(c.get("spot_max_vcpus") or 0) + int(c.get("ondemand_max_vcpus") or 0)

    # Cùng cấu hình đoạn nhưng khác công suất (S2: 8 so với 16 vCPU) phải đọc được ở hai dòng riêng.
    picked.sort(key=lambda r: (capacity(r), r["date"], r["chunk"]["vcpu"], r["id"]))
    rows = []
    for r in picked:
        chunk = r["chunk"]
        phase = r["timings_s"].get("chunks")
        vs = r.get("vcpu_seconds")
        total = capacity(r)
        slots = chunk.get("slots") or (total // chunk["vcpu"] if total and chunk.get("vcpu") else None)
        rows.append([
            f"{chunk['count']} $\\times$ {chunk['vcpu']} vCPU ({esc(env_name(r))})",
            str(total) if total else "n/a",
            str(slots) if slots else "n/a",
            minutes(phase) if phase else "n/a",
            minutes(r["timings_s"]["end_to_end"]),
            f"{vs:,}".replace(",", "\\,") if vs else "n/a",
        ])
    header = ["CONFIGURATION", "CAPACITY (VCPU)", "SLOTS", "CHUNK PHASE (MIN)", "END TO READY (MIN)", "VCPU-SECONDS"]
    return table("X r r r r r", header, rows), picked


def table_concurrency(runs):
    """Bốn video 25 phút nộp cùng lúc."""
    picked = [r for r in runs if r["concurrency"] == 4 and r["video"]["label"] == "25min-1080p"]
    picked.sort(key=lambda r: r["queue_position"])
    rows = []
    for r in picked:
        t = r["timings_s"]
        rows.append([
            str(r["queue_position"]),
            minutes(t["chunks_start"]),
            minutes(t["chunks_end"]),
            minutes(t["end_to_end"]),
        ])
    header = ["SUBMISSION ORDER", "CHUNKS START (MIN)", "CHUNKS END (MIN)", "READY (MIN)"]
    return table("X r r r", header, rows), picked


def table_single_vs_chunked(runs):
    """So đường một-job với đường chia đoạn ở video 5, 10, 15 phút."""
    by_label = {}
    for r in runs:
        if r["video"]["label"] in ("5min-1080p30", "10min-1080p30", "15min-1080p30") and "end_to_end" in r["timings_s"]:
            by_label.setdefault(r["video"]["label"], {})[r["path"]] = r
    rows, used = [], []
    for label in sorted(by_label, key=lambda k: int(k.split("min")[0])):
        single, chunked = by_label[label].get("single"), by_label[label].get("chunked")
        if not single or not chunked:
            continue
        used += [single, chunked]
        s_est = single["provenance"] == "estimated"
        s_sec, c_sec = single["timings_s"]["end_to_end"], chunked["timings_s"]["end_to_end"]
        mark = "$\\approx$ " if s_est else ""
        rows.append([
            f"{int(label.split('min')[0])} min",
            mark + minutes(s_sec),
            minutes(c_sec),
            mark + f"{s_sec / c_sec:.1f}",
        ])
    header = ["VIDEO LENGTH", "SINGLE JOB (MIN)", "CHUNKED (MIN)", "SPEED-UP"]
    return table("X r r r", header, rows), used


def table_four_hours(runs):
    # Nhiều lần đo 4 giờ: lấy lượt mới nhất (id có ngày), ưu tiên bản ghi có đủ các bước.
    candidates = [r for r in runs if r["video"]["label"] == "4h-1080p30" and r["path"] == "chunked"]
    if not candidates:
        return None, []
    run = sorted(candidates, key=lambda r: (r["date"], r["id"]))[-1]
    t, c = run["timings_s"], run["chunk"]

    if "audio_64k" in t and "audio_128k" in t:
        audio = f"{minutes(t['audio_64k'])} / {minutes(t['audio_128k'])}"
    elif t.get("audio") is not None:
        audio = minutes(t["audio"])  # lần đo mới chỉ ghi job âm thanh chậm nhất
    else:
        audio = "n/a"
    slots = c.get("slots")
    concurrency = f", {slots} at a time" if slots else ""
    rows = [
        ["Planner (Lambda submit to child jobs)", minutes(t["planner"]) if t.get("planner") is not None else "n/a"],
        ["Audio 64 kbit/s and 128 kbit/s (in parallel)", audio],
        [f"{c['count']} chunk jobs{concurrency}, {c['vcpu']} vCPU each", minutes(t["chunks"])],
        ["Finalizer (playlists, thumbnail, moderation, READY)", minutes(t["finalize"]) if t.get("finalize") is not None else "n/a"],
        ["\\textbf{Upload complete to READY}", "\\textbf{" + minutes(t["end_to_end"]) + "}"],
    ]
    return table("X r", ["STEP", "MINUTES"], rows), [run]


def table_legacy_timing():
    if not LEGACY.exists():
        return None, []
    data = json.loads(LEGACY.read_text(encoding="utf-8"))
    groups = {}
    for rec in data:
        label = rec["label"].lower()
        four = "4vcpu" in label
        key = label.replace("-4vcpu", "")
        if key not in LEGACY_LABELS or rec.get("finalStatus") != "READY":
            continue
        groups.setdefault((key, 4 if four else 1), []).append(rec)
    rows = []
    for (key, vcpu), recs in sorted(groups.items(), key=lambda kv: (kv[0][1], list(LEGACY_LABELS).index(kv[0][0]))):
        pipe = [r["timings"]["transcodePipelineSec"] for r in recs]
        factor = [r["realtimeFactor"] for r in recs]
        rows.append([
            LEGACY_LABELS[key],
            str(vcpu),
            str(len(recs)),
            f"{statistics.median(pipe):.0f}",
            f"{min(pipe):.0f}--{max(pipe):.0f}" if len(pipe) > 1 else "n/a",
            f"{statistics.median(factor):.2f}",
        ])
    header = ["SOURCE", "VCPU", "RUNS", "MEDIAN (S)", "RANGE (S)", "REAL-TIME FACTOR"]
    return table("X r r r r r", header, rows), [{"_file": LEGACY.relative_to(ROOT).as_posix(), "id": "transcode-timing", "date": "2026-08"}]


TABLES = [
    ("tab-chunk-config-25min.tex", "25-minute video, chunked path, by chunk configuration", table_scaling_25min,
     "Chương đánh giá, mục chuyển mã chia đoạn"),
    ("tab-concurrent-four-videos.tex", "Four 25-minute videos submitted together", table_concurrency,
     "Chương đánh giá, mục nhiều video cùng lúc"),
    ("tab-single-vs-chunked.tex", "Single-job path against chunked path, 5 to 15 minutes", table_single_vs_chunked,
     "Chương đánh giá, mục ngưỡng chia đoạn"),
    ("tab-four-hour-breakdown.tex", "Four-hour video, time per step", table_four_hours,
     "Chương đánh giá, mục video 4 giờ"),
]


def build():
    runs = load_runs()
    outputs, used_by = {}, {}
    for name, _title, fn, _where in TABLES:
        text, used = fn(runs)
        if text:
            outputs[name] = text
            used_by[name] = used
    text, used = table_legacy_timing()
    if text:
        outputs["tab-transcode-timing-single-job.tex"] = text
        used_by["tab-transcode-timing-single-job.tex"] = used
    return runs, outputs, used_by


def build_index(runs, outputs, used_by):
    titles = {n: (t, w) for n, t, _f, w in TABLES}
    titles["tab-transcode-timing-single-job.tex"] = (
        "Single-job path, 100 MB to 1 GB, 1 vCPU against 4 vCPU", "Chương đánh giá, mục thời gian chuyển mã theo dung lượng")
    lines = [
        "# Mục lục số liệu đo",
        "",
        "Tệp này do `scripts/results/build-report-tables.py` sinh ra; đừng sửa tay. Số liệu gốc là các tệp JSON trong `docs/results/`.",
        "Chạy lại: `PYTHONUTF8=1 python scripts/results/build-report-tables.py`.",
        "",
        "## Bảng của báo cáo và nguồn của chúng",
        "",
        "| Tệp bảng (`report/generated/`) | Nội dung | Dùng ở | Lượt đo nguồn |",
        "|---|---|---|---|",
    ]
    for name in sorted(outputs):
        title, where = titles.get(name, (name, ""))
        sources = ", ".join(sorted({u["id"] for u in used_by[name]}))
        lines.append(f"| `{name}` | {title} | {where} | {sources} |")
    lines += [
        "",
        "## Các lượt đo trong `docs/results/runs/`",
        "",
        "| Mã lượt đo | Ngày | Môi trường | Đường | Video | Đồng thời | READY (phút) | Mức chắc chắn | Nguồn |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in sorted(runs, key=lambda x: (x["date"], x["id"])):
        e2e = r["timings_s"].get("end_to_end")
        lines.append(
            f"| `{r['id']}` | {r['date']} | {r['environment']} | {r['path']} | {r['video']['label']} | {r['concurrency']} | "
            f"{minutes(e2e) if e2e else '-'} | {r['provenance']} | `{r['source']}` |"
        )
    lines += [
        "",
        "Mức chắc chắn: `measured` đo trực tiếp, `derived` tính từ số đo (ví dụ đổi phút ra giây), `estimated` suy ra bằng tỉ lệ và chưa đo; "
        "bản ghi `estimated` phải được ghi rõ là ước tính khi đưa vào báo cáo.",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="không ghi, trả lỗi nếu tệp sinh ra khác bản hiện có")
    args = parser.parse_args()

    sys.stdout.reconfigure(encoding="utf-8")
    runs, outputs, used_by = build()
    index_text = build_index(runs, outputs, used_by)

    stale = []
    if not args.check:
        OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, text in outputs.items():
        target = OUT_DIR / name
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != text:
                stale.append(target.relative_to(ROOT).as_posix())
        else:
            target.write_text(text, encoding="utf-8", newline="\n")
    if args.check:
        if not INDEX.exists() or INDEX.read_text(encoding="utf-8") != index_text:
            stale.append(INDEX.relative_to(ROOT).as_posix())
        if stale:
            print("Tệp sinh ra đã cũ so với dữ liệu: " + ", ".join(stale))
            return 1
        print("Bảng và mục lục khớp với dữ liệu.")
        return 0

    INDEX.write_text(index_text, encoding="utf-8", newline="\n")
    print(f"{len(runs)} lượt đo, {len(outputs)} bảng -> {OUT_DIR.relative_to(ROOT).as_posix()}, mục lục -> {INDEX.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
